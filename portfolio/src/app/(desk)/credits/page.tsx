import type { Metadata } from 'next'
import Link from 'next/link'
import { getDeskContent } from '@/lib/desk/content'
import credits from '../../../../assets/credits.json'

export async function generateMetadata(): Promise<Metadata> {
  const { name } = await getDeskContent()
  return { title: name ? `Credits · ${name}` : 'Credits' }
}

const LICENSE_URLS: Record<string, string> = {
  'CC0-1.0': 'https://creativecommons.org/publicdomain/zero/1.0/',
  'CC-BY-3.0': 'https://creativecommons.org/licenses/by/3.0/',
  'CC-BY-4.0': 'https://creativecommons.org/licenses/by/4.0/',
  'PDDL-1.0': 'https://opendatacommons.org/licenses/pddl/1-0/',
  'OFL-1.1': 'https://openfontlicense.org/',
  'Apache-2.0': 'https://www.apache.org/licenses/LICENSE-2.0',
}

const ORIGIN_LABEL: Record<string, string> = {
  library: 'open library',
  scan: 'scanned by Ben',
  handmade: 'made by Ben',
}

export default function CreditsPage() {
  const sorted = [...credits].sort((a, b) => a.title.localeCompare(b.title))
  return (
    <main className="h-full overflow-y-auto px-4 py-12 font-mono text-sm">
      <div className="mx-auto max-w-2xl">
        <Link href="/" className="underline">
          ← back to the desk
        </Link>
        <h1 className="mt-6 text-2xl font-bold">Credits</h1>
        <p className="mt-2 opacity-70">
          Every 3D model, texture and font in the room was made by a person, not generated by AI.
        </p>
        <p className="mt-2 opacity-70">
          All assets were optimized for the web: textures resized and converted to WebP, meshes
          compressed with meshopt. Other changes are listed per item.
        </p>
        <ul className="mt-8 space-y-4">
          {sorted.map((c) => (
            <li key={c.id}>
              <a href={c.source_url} className="font-bold underline">
                {c.title}
              </a>{' '}
              by {c.authors.join(', ')} ·{' '}
              {LICENSE_URLS[c.license] ? (
                <a href={LICENSE_URLS[c.license]} className="underline">
                  {c.license}
                </a>
              ) : (
                c.license
              )}{' '}
              · {ORIGIN_LABEL[c.origin] ?? c.origin}
              {c.modifications.length > 0 && (
                <span className="block opacity-70">changes: {c.modifications.join('; ')}</span>
              )}
            </li>
          ))}
        </ul>
      </div>
    </main>
  )
}
